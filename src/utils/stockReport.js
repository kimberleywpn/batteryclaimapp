import { groupStockByModel } from "./stockGrouping.js";

export const stockViews = { in: "In Stock", out: "Out", cancelled: "Cancelled", movements: "Movements" };
const movementLabels = { stock_in: "Stock In", available: "Marked Available", updated: "Details Updated", sold: "Sold", spare: "Issued As Spare", disposed: "Disposed", reversed: "Stock-Out Corrected", cancelled: "Stock In Cancelled" };
const value = input => input ?? "";
const number = input => input === "" || input == null ? "" : Number.isFinite(Number(input)) ? Number(input) : String(input);

export function filterStockRecords({ items, movements, view, query = "", brand, startDate, endDate }) {
  const needle = query.trim().toLowerCase();
  const byId = new Map(items.map(item => [item.id, item]));
  const rows = view === "movements" ? movements : items.filter(item => item.state === (view === "in" ? "available" : view));
  return rows.filter(row => {
    const item = view === "movements" ? byId.get(row.itemId) : row;
    const date = view === "movements" ? row.date : view === "out" ? row.out?.date : view === "cancelled" ? row.cancellation?.date : row.receivedDate;
    return (!needle || [row.serial, row.model, item?.brand, item?.description, item?.dealerName, item?.branchName].join(" ").toLowerCase().includes(needle)) &&
      (!brand || item?.brand === brand) && (!startDate || date >= startDate) && (!endDate || date <= endDate);
  });
}

// Date-only serials avoid timezone shifts and remain sortable dates in Excel.
function excelDate(input) {
  if (!input) return "";
  const text = String(input).slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(text)) return String(input);
  const time = Date.parse(`${text}T00:00:00Z`);
  if (!Number.isFinite(time) || new Date(time).toISOString().slice(0, 10) !== text) return String(input);
  return { t: "n", v: time / 86400000 + 25569, z: "dd-mm-yyyy" };
}

export function stockReportSheets({ view, rows, items, query = "", brand, startDate, endDate, generatedAt, generatedBy }) {
  const movementView = view === "movements";
  const groups = movementView ? [] : groupStockByModel(rows);
  const summary = [
    ["Battery Stock Report", ""],
    ["Report", stockViews[view]],
    ["Generated At", generatedAt],
    ["Generated By", generatedBy],
    ["Scope", "All matching records across all pages"],
    ["Search", query.trim() || "All"],
    ["Brand", brand || "All"],
    ["Date Filter Uses", movementView ? "Movement Date" : view === "out" ? "Stock-Out Date" : view === "cancelled" ? "Cancellation Date" : "Stock-In Date"],
    ["From", startDate ? excelDate(startDate) : "Any"],
    ["To", endDate ? excelDate(endDate) : "Any"],
    [movementView ? "Movement Records" : "Batteries", rows.length],
    ...(!movementView ? [["Brand / Model Groups", groups.length]] : []),
  ];
  if (movementView) {
    const byId = new Map(items.map(item => [item.id, item]));
    return [
      { name: "Summary", rows: summary, widths: [26, 52] },
      { name: "Movements", rows: [
        ["Movement Date", "Recorded At", "Movement", "Serial Number", "Battery Model", "Brand", "Recorded By", "Recipient", "Reference", "Selling Price (MYR)", "Reason / Remarks", "Stock ID", "Movement ID"],
        ...rows.map(event => [excelDate(event.date), value(event.recordedAt), movementLabels[event.kind] || event.kind, value(event.serial), value(event.model), value(byId.get(event.itemId)?.brand), value(event.actor), value(event.details?.recipient), value(event.details?.reference), number(event.details?.price), event.details?.reason || event.details?.remarks || "", event.itemId, event.id]),
      ] },
    ];
  }
  return [
    { name: "Summary", rows: summary, widths: [26, 52] },
    { name: "Stock By Model", rows: [
      ["Battery Model", "Brand", "Description", "Quantity"],
      ...groups.map(group => [group.model || "Model Not Recorded", value(group.brand), value(group.description), group.items.length]),
    ] },
    { name: "Batteries", rows: [
      ["Previous Serial Number", "Battery Model", "Brand", "Description", "Status", "Stock-In Date", "Used Months", "OCV (V)", "CCA (A)", "Test Result", "Last Test Update", "Dealer", "Branch Code", "Remarks", "Stock-Out Date", "Stock-Out Type", "Recipient", "Reference", "Selling Price (MYR)", "Stock-Out Remarks", "Cancellation Date", "Cancellation Reason", "Source Case Number", "Source Claim ID", "Stock ID"],
      ...rows.map(item => [item.sourceClaim?.serial || item.serial, value(item.model), value(item.brand), value(item.description), item.state === "out" ? "Out" : item.state === "cancelled" ? "Cancelled" : "Available", excelDate(item.receivedDate), number(item.usedMonths), number(item.ocv), number(item.cca), value(item.testResult), excelDate(item.checkedDate), value(item.dealerName), value(item.branchName), value(item.notes), excelDate(item.out?.date), movementLabels[item.out?.type] || "", value(item.out?.recipient), value(item.out?.reference), number(item.out?.price), value(item.out?.remarks), excelDate(item.cancellation?.date), value(item.cancellation?.reason), value(item.sourceClaim?.caseNumber), value(item.sourceClaim?.id), item.id]),
    ] },
  ];
}

export async function stockReportWorkbook(options) {
  const XLSX = await import("xlsx");
  const workbook = XLSX.utils.book_new();
  for (const report of stockReportSheets(options)) {
    const sheet = XLSX.utils.aoa_to_sheet(report.rows);
    sheet["!cols"] = report.rows[0].map((_, index) => ({ wch: report.widths?.[index] ?? Math.min(42, Math.max(14, ...report.rows.slice(0, 251).map(row => typeof row[index] === "object" ? 14 : String(row[index] ?? "").length + 2))) }));
    if (report.name !== "Summary") sheet["!autofilter"] = { ref: sheet["!ref"] };
    XLSX.utils.book_append_sheet(workbook, sheet, report.name);
  }
  return XLSX.write(workbook, { bookType: "xlsx", type: "array" });
}

export async function downloadStockReport(options, filename) {
  const data = await stockReportWorkbook(options);
  const url = URL.createObjectURL(new Blob([data], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }));
  const link = document.createElement("a");
  link.href = url; link.download = filename;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
